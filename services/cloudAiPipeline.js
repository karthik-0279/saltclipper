const { spawn } = require('child_process');
const path = require('path');
const fs = require('fs');

const PYTHON_PATH = process.env.PYTHON_PATH || (
  fs.existsSync('C:/Users/goudk/AppData/Local/Python/bin/python.exe')
    ? 'C:/Users/goudk/AppData/Local/Python/bin/python.exe'
    : 'python'
);

/**
 * Generate Script directly via Google Gemini API (Native Node.js REST call)
 */
async function generateScriptWithGemini(summaryText, options = {}) {
  const apiKey = (process.env.GEMINI_API_KEY || '').trim();
  if (!apiKey) {
    throw new Error('GEMINI_API_KEY is not configured in .env or environment.');
  }

  const model = options.model || 'gemini-2.5-flash';
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;

  const prompt = options.customPrompt || `
You are an expert short-form video scriptwriter (YouTube Shorts / Reels / TikTok).
Based on the following data from Google Cloud database, generate a viral 30-60 second video clip script.

TOPIC/DATA:
${summaryText}

Format the output strictly as:
1. Hook (First 3 seconds): Catchy opening line to stop scrolling
2. Core Value/Story (3-4 concise bullet points)
3. Call To Action (CTA): High conversion engagement prompt
4. Recommended Visual / Caption Ideas
`;

  const response = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [{
        parts: [{ text: prompt }]
      }],
      generationConfig: {
        temperature: 0.7,
        maxOutputTokens: 1000
      }
    })
  });

  if (!response.ok) {
    const errorBody = await response.text();
    throw new Error(`Gemini API Error (${response.status}): ${errorBody}`);
  }

  const json = await response.json();
  const script = json.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!script) {
    throw new Error('No script generated by Gemini AI.');
  }

  return script;
}

/**
 * Execute cloud_ai_pipeline.py to fetch latest record from Google Cloud Firestore
 * and generate script.
 */
function runPythonPipeline(collectionName = 'project_updates') {
  return new Promise((resolve, reject) => {
    const scriptPath = path.join(__dirname, '..', 'cloud_ai_pipeline.py');
    const child = spawn(PYTHON_PATH, [scriptPath, collectionName], {
      cwd: path.join(__dirname, '..'),
      env: { ...process.env }
    });

    let stdout = '';
    let stderr = '';

    child.stdout.on('data', chunk => { stdout += chunk.toString(); });
    child.stderr.on('data', chunk => { stderr += chunk.toString(); });

    child.on('close', code => {
      if (code !== 0) {
        return reject(new Error(`Python pipeline failed (exit code ${code}): ${stderr || stdout}`));
      }
      resolve({ output: stdout, error: stderr });
    });
  });
}

module.exports = {
  generateScriptWithGemini,
  runPythonPipeline
};

