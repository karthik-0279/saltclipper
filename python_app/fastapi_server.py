# 2. YouTube OAuth & Authentication Helper
# ==========================================

def get_authenticated_youtube_client():
    """
    Builds an authorized YouTube Data API v3 client using stored tokens in youtube_tokens.json
    and credentials from .env. Automatically refreshes expired access tokens.
    """
    if not TOKENS_FILE.exists():
        raise HTTPException(
            status_code=401, 
            detail="youtube_tokens.json not found. Please connect your YouTube account first."
        )

    try:
        with open(TOKENS_FILE, "r", encoding="utf-8") as f:
            tokens = json.load(f)
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to read youtube_tokens.json: {str(e)}")

    client_id = os.getenv("GOOGLE_CLIENT_ID", "").strip()
    client_secret = os.getenv("GOOGLE_CLIENT_SECRET", "").strip()

    creds = Credentials(
        token=tokens.get("access_token"),
        refresh_token=tokens.get("refresh_token"),
        token_uri="https://oauth2.googleapis.com/token",
        client_id=client_id,
        client_secret=client_secret,
        scopes=["https://www.googleapis.com/auth/youtube.upload", "https://www.googleapis.com/auth/youtube.readonly"]
    )

    # Refresh expired token if needed
    if creds.expired and creds.refresh_token:
        try:
            creds.refresh(Request())
            # Save refreshed access token back to file
            tokens["access_token"] = creds.token
            with open(TOKENS_FILE, "w", encoding="utf-8") as f:
                json.dump(tokens, f, indent=2)
            print("[YOUTUBE AUTH] Successfully refreshed Google access token.")
        except Exception as err:
            print(f"[YOUTUBE AUTH WARNING] Token refresh failed: {err}")

    return googleapiclient.discovery.build("youtube", "v3", credentials=creds)


# ==========================================
# 3. Core YouTube Upload Logic
# ==========================================

def upload_to_youtube(
    file_path: str,
    title: str,
    description: str = "Auto-generated by AI Pipeline #Shorts",
    privacy_status: str = "public",
    schedule_time: Optional[datetime.datetime] = None
) -> Dict[str, Any]:
    """
    Uploads a short video clip to YouTube.
    If schedule_time is provided, sets privacyStatus to 'private' and publishAt to future ISO timestamp.
    """
    resolved_path = Path(file_path)
    if not resolved_path.is_absolute():
        resolved_path = BASE_DIR / resolved_path

    if not resolved_path.exists():
        err_msg = f"Video file not found at: {resolved_path}"
        print(f"❌ [UPLOAD ERROR] {err_msg}")
        return {"status": "error", "error": err_msg}

    youtube = get_authenticated_youtube_client()

    # Base snippet metadata
    tags = ["shorts", "automation", "ai", "viral"]
    snippet = {
        "title": title[:100],
        "description": description,
        "tags": tags,
        "categoryId": "22"  # People & Blogs
    }

    # Status setup
    status: Dict[str, Any] = {
        "selfDeclaredMadeForKids": False
    }

    # Handle YouTube Scheduled Publishing
    if schedule_time:
        # YouTube requires scheduled videos to have privacyStatus="private" + publishAt timestamp
        # Ensure UTC timezone format: YYYY-MM-DDTHH:MM:SS.000Z
        utc_time = schedule_time.astimezone(datetime.timezone.utc)
        iso_str = utc_time.strftime("%Y-%m-%dT%H:%M:%S.000Z")
        status["privacyStatus"] = "private"
        status["publishAt"] = iso_str
        print(f"⏰ [SCHEDULE] Video scheduled for automated release at: {iso_str}")
    else:
        status["privacyStatus"] = privacy_status

    body = {
        "snippet": snippet,
        "status": status
    }

    media = MediaFileUpload(
        str(resolved_path), 
        mimetype="video/mp4", 
        chunksize=1024 * 1024 * 4, # 4MB chunks
        resumable=True
    )

    print(f"🚀 [UPLOAD] Uploading '{resolved_path.name}' to YouTube...")
    try:
        request = youtube.videos().insert(
            part="snippet,status",
            body=body,
            media_body=media
        )
        response = None
        while response is None:
            status_obj, response = request.next_chunk()
            if status_obj:
                print(f"   Progress: {int(status_obj.progress() * 100)}%")

        video_id = response.get("id")
        shorts_url = f"https://youtube.com/shorts/{video_id}"
        print(f"✅ [SUCCESS] Published to YouTube! Shorts Link: {shorts_url}")
        return {
            "status": "success",
            "video_id": video_id,
            "shorts_url": shorts_url,
            "scheduled_at": status.get("publishAt"),
            "privacy": status.get("privacyStatus")
        }
    except googleapiclient.errors.HttpError as err:
        print(f"❌ [YOUTUBE API HTTP ERROR] {err}")
        return {"status": "error", "error": str(err)}
    except Exception as err:
        print(f"❌ [UNEXPECTED ERROR] {err}")
        return {"status": "error", "error": str(err)}


